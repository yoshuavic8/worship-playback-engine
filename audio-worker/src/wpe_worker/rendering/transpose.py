"""Offline transpose (pitch shift without tempo change) with Signalsmith Stretch (MIT).

Rendered once before the service and cached per key in `<song>/transpose/<tag>/`.
Live playback only ever reads these files; nothing is rendered while playing.

Rule: only tonal stems are pitched. Drums/percussion, the click, voice cues and any
guide/cue stem are NEVER pitched (the click and cues are generated by the app at
playback time and are not stems at all).
"""

from __future__ import annotations

import json
import os
import shutil
import time
from dataclasses import dataclass, field
from pathlib import Path

import numpy as np

from ..audio import io
from ..protocol import WorkerError, emit, log, progress

MAX_SEMITONES = 4
# Tonal stems in render order. "vocals" is the guide vocal (monitor only).
PITCHED = ("other", "bass", "vocals")
NEVER_PITCHED = ("drums", "percussion", "click", "cue", "cues", "guide_cue")


def pitched_stems(available: list[str] | dict) -> list[str]:
    """Which of the available stems get transposed (drums/click/cue never)."""
    names = list(available)
    return [k for k in PITCHED if k in names and k not in NEVER_PITCHED]


def tag(semitones: int) -> str:
    """Cache folder name: +2 → p2, -3 → m3."""
    if semitones == 0:
        raise ValueError("0 semitones is the original key")
    return f"p{semitones}" if semitones > 0 else f"m{-semitones}"


def tonality_limit(stem: str, sr: int) -> float:
    """Above this frequency the spectral envelope is kept instead of shifted.

    The python binding has no explicit formant control; keeping the upper spectrum
    in place is how Signalsmith Stretch preserves timbre (it keeps vocals and
    keys from sounding "chipmunky"). Bass is fully tonal.
    """
    if stem == "bass":
        return 0.0
    hz = 5000.0 if stem == "vocals" else 8000.0
    return hz / sr


def shift(audio: np.ndarray, sr: int, semitones: int, stem: str = "other") -> np.ndarray:
    """Pitch-shift (channels, samples) float32 audio. Length and timing are preserved."""
    if semitones == 0:
        return audio
    try:
        import python_stretch as ps
    except ImportError as e:  # pragma: no cover - depends on the environment
        raise WorkerError("stretch_missing", "Signalsmith Stretch (python-stretch) is not installed", str(e)) from e
    a = np.ascontiguousarray(audio, dtype=np.float32)
    st = ps.Signalsmith.Stretch()
    st.preset(int(a.shape[0]), float(sr))
    st.setTransposeSemitones(float(semitones), tonality_limit(stem, sr))
    out = np.asarray(st.process(a), dtype=np.float32)
    out = io.fit_length(out, a.shape[-1])
    # Never clip: a shifted stem can peak slightly higher than the source.
    peak = float(np.max(np.abs(out))) if out.size else 0.0
    if peak > 0.999:
        out *= 0.999 / peak
    return out


@dataclass
class TransposeRequest:
    song_id: str
    song_dir: str
    stems: dict[str, str]
    semitones: list[int] = field(default_factory=list)

    @staticmethod
    def parse(d: dict) -> "TransposeRequest":
        if d.get("type") != "transpose_song":
            raise WorkerError("bad_request", f"unsupported request type {d.get('type')!r}")
        song_dir = d.get("songDir")
        if not isinstance(song_dir, str) or not song_dir:
            raise WorkerError("bad_request", "missing field songDir")
        stems = {str(k): str(v) for k, v in (d.get("stems") or {}).items() if v}
        semis = []
        for s in d.get("semitones") or []:
            s = int(s)
            if s == 0 or abs(s) > MAX_SEMITONES:
                raise WorkerError("bad_request", f"transpose must be -{MAX_SEMITONES}..+{MAX_SEMITONES}, got {s}")
            if s not in semis:
                semis.append(s)
        return TransposeRequest(str(d.get("songId") or ""), song_dir, stems, semis)


def _signature(song: Path, rel: str) -> dict:
    st = os.stat(song / rel)
    return {"path": rel, "size": st.st_size, "mtime": int(st.st_mtime)}


def run(req: TransposeRequest) -> dict:
    song = Path(req.song_dir)
    todo = pitched_stems(req.stems)
    if not todo:
        raise WorkerError("no_stems", "Transpose needs separated stems. Prepare the song with stem separation first.")
    for k in todo:
        if not (song / req.stems[k]).is_file():
            raise WorkerError("no_stems", f"Stem {k} is missing. Prepare the song again.")
    total = max(1, len(todo) * len(req.semitones))
    step = 0
    renders: dict[str, dict[str, str]] = {}
    t0 = time.time()
    cache: dict[str, tuple[np.ndarray, int]] = {}
    for semis in req.semitones:
        final = song / "transpose" / tag(semis)
        tmp = song / "transpose" / f".{tag(semis)}.tmp"
        shutil.rmtree(tmp, ignore_errors=True)
        tmp.mkdir(parents=True, exist_ok=True)
        files: dict[str, str] = {}
        for stem in todo:
            progress("transpose", step / total, f"{'+' if semis > 0 else ''}{semis}: {stem}")
            if stem not in cache:
                cache[stem] = io.read(str(song / req.stems[stem]))
            audio, sr = cache[stem]
            out = shift(audio, sr, semis, stem)
            if not np.isfinite(out).all():
                raise WorkerError("transpose_failed", f"{stem} produced invalid samples")
            io.write(str(tmp / f"{stem}.wav"), out, sr)
            files[stem] = f"transpose/{tag(semis)}/{stem}.wav"
            step += 1
        (tmp / "done.json").write_text(json.dumps({
            "semitones": semis,
            "engine": "signalsmith-stretch",
            "stems": {k: _signature(song, req.stems[k]) for k in todo},
            "notPitched": [k for k in req.stems if k not in todo],
        }))
        shutil.rmtree(final, ignore_errors=True)
        os.replace(tmp, final)
        renders[str(semis)] = files
        log(f"transpose {semis:+d} rendered ({', '.join(todo)})")
    progress("transpose", 1.0, "Ready")
    return {"renders": renders, "seconds": round(time.time() - t0, 2)}


def run_and_emit(req: TransposeRequest) -> int:
    try:
        emit("result", **run(req))
        return 0
    except WorkerError as e:
        emit("error", code=e.code, message=e.message, details=e.details)
        return 2
    except MemoryError as e:
        emit("error", code="out_of_memory", message="Out of memory", details=repr(e))
        return 3
    except Exception as e:  # noqa: BLE001
        import traceback

        emit("error", code="transpose_failed", message=str(e) or repr(e), details=traceback.format_exc())
        return 1
